use crate::rpc::types::pubsub;
///! Mazze PUB-SUB rpc interface.
use jsonrpsee::proc_macros::rpc;

/// Mazze PUB-SUB rpc interface.
#[rpc(server)]
pub trait PubSub {
    /// Subscribes to Mazze subscription.
    ///
    /// Notifications are sent as `mazze_subscription`; `mazze_unsubscribe`
    /// (generated by jsonrpsee) cancels a subscription of the calling
    /// connection and returns whether it existed.
    #[subscription(
        name = "mazze_subscribe" => "mazze_subscription",
        unsubscribe = "mazze_unsubscribe",
        item = pubsub::Result
    )]
    fn subscribe(&self, kind: pubsub::Kind, params: Option<pubsub::Params>);
}
